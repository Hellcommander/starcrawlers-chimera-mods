"""Procedural summon models for the Arendeth classes (original geometry and textures, written as OBJ + PNG).
  gloomcap  - Gloomspore Warden's Gloomcap: a squat fungus with a domed, glowing-pored cap, gills and root tendrils
  spillnode - Entropy Weaver's Spillnode: a floating knot of runaway power thread around a bright core
  omega_wisp - Rimelight Seer's Omega Hoarlight: a faceted core of mind light in a tilted halo, ringed by frost shards
  hoarlight  - Rimelight Seer's Hoarlight: a small teardrop crystal of mind light with three splinters (its halo and
               motes are particles, see make_wisp_assets.py)
  shardspark - Rimelight Seer's Shardspark: a star of three crossed frost splinters torn out of a heavy cast
Usage: python make_summon_models.py <Mods folder> [model ...]   (no names = all)
OBJ convention (same as make_kinetics_models.py): Y up, right-handed, counter-clockwise front faces, 1 unit = 1 m.
Unlike the Kinetics props these are organic, so vertices are shared and normals smoothed."""
import math, os, sys, random
from PIL import Image, ImageDraw, ImageFilter

TAU = 2 * math.pi


def sub(a, b): return (a[0] - b[0], a[1] - b[1], a[2] - b[2])
def add(a, b): return (a[0] + b[0], a[1] + b[1], a[2] + b[2])
def mul(a, k): return (a[0] * k, a[1] * k, a[2] * k)
def dot(a, b): return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]
def cross(a, b): return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])
def norm(a):
    l = math.sqrt(dot(a, a)) or 1.0
    return (a[0] / l, a[1] / l, a[2] / l)


class Mesh:
    """Indexed mesh: each vertex has a position and a UV; normals are smoothed over equal positions."""
    def __init__(self):
        self.v, self.vt, self.f = [], [], []

    def vert(self, p, uv):
        self.v.append(p); self.vt.append(uv)
        return len(self.v) - 1

    def grid(self, rows, closed_u=True, outward=None):
        """rows: list of rings, each a list of (pos, uv). Faces joined ring to ring (the ring's last point
        repeats the first when closed, for the UV seam). `outward(p)` picks the side the faces look at."""
        idx = [[self.vert(p, uv) for (p, uv) in ring] for ring in rows]
        for r in range(len(idx) - 1):
            a, b = idx[r], idx[r + 1]
            for i in range(len(a) - 1):
                self.face(a[i], a[i + 1], b[i + 1], outward)
                self.face(a[i], b[i + 1], b[i], outward)

    def face(self, i, j, k, outward=None):
        p0, p1, p2 = self.v[i], self.v[j], self.v[k]
        n = cross(sub(p1, p0), sub(p2, p0))
        if dot(n, n) < 1e-14: return
        if outward is not None:
            c = mul(add(add(p0, p1), p2), 1 / 3)
            if dot(n, outward(c)) < 0: j, k = k, j
        self.f.append((i, j, k))

    def normals(self):
        acc = {}
        key = lambda p: (round(p[0], 4), round(p[1], 4), round(p[2], 4))
        for (i, j, k) in self.f:
            n = cross(sub(self.v[j], self.v[i]), sub(self.v[k], self.v[i]))  # area-weighted
            for x in (i, j, k):
                kk = key(self.v[x]); s = acc.get(kk, (0, 0, 0)); acc[kk] = add(s, n)
        return [norm(acc.get(key(p), (0, 1, 0))) for p in self.v]

    def save(self, path, name):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        vn = self.normals()
        with open(path, 'w') as o:
            o.write(f'# {name} - generated by make_summon_models.py\n')
            for p in self.v: o.write('v %.5f %.5f %.5f\n' % p)
            for t in self.vt: o.write('vt %.5f %.5f\n' % t)
            for n in vn: o.write('vn %.5f %.5f %.5f\n' % n)
            for (i, j, k) in self.f: o.write(f'f {i+1}/{i+1}/{i+1} {j+1}/{j+1}/{j+1} {k+1}/{k+1}/{k+1}\n')
        print('wrote', path, len(self.v), 'verts', len(self.f), 'tris')


def region(u, v, box):
    """Maps 0..1 uv into an atlas box (u0, v0, u1, v1)."""
    return (box[0] + (box[2] - box[0]) * u, box[1] + (box[3] - box[1]) * v)


# ---------------------------------------------------------------------------------------------- Gloomcap

CAP_TOP, GILLS, STEM, ROOTS = (0, .5, .5, 1), (.5, .5, 1, 1), (0, 0, .5, .5), (.5, 0, 1, .5)


def lathe(m, profile, seg, box, wave=None, tilt=None, outward=None):
    """Spins (radius, y) points around Y. wave(theta, t) scales the radius, tilt(p) bends the result."""
    rows = []
    n = len(profile)
    for pi, (r, y) in enumerate(profile):
        t = pi / (n - 1)
        ring = []
        for s in range(seg + 1):
            th = TAU * s / seg
            rr = r * (wave(th, t) if wave else 1.0)
            p = (rr * math.cos(th), y, rr * math.sin(th))
            if tilt: p = tilt(p)
            ring.append((p, region(s / seg, t, box)))
        rows.append(ring)
    m.grid(rows, outward=outward)


def gloomcap(out):
    random.seed(7)
    m = Mesh()
    lean = math.radians(6)
    def tilt(p):
        # the cap leans a little, as if it grew towards something
        y = p[1]
        if y < 0.45: return p
        a = lean * min(1.0, (y - 0.45) / 0.3)
        return (p[0] * math.cos(a) - (y - 0.45) * math.sin(a) * 0.4, y, p[2])
    wave = lambda th, t: 1.0 + 0.06 * math.sin(5 * th + 0.7) * t + 0.03 * math.sin(11 * th)
    away_y = lambda c: (c[0], 0.0, c[2])

    # stem: a bulb at the foot, a waist, then a collar under the cap
    stem = [(0.20, 0.0), (0.23, 0.04), (0.21, 0.12), (0.15, 0.26), (0.12, 0.38), (0.13, 0.48), (0.16, 0.55)]
    lathe(m, stem, 18, STEM, wave=lambda th, t: 1.0 + 0.05 * math.sin(3 * th), tilt=tilt, outward=away_y)

    # cap top: from a slightly curled-under rim up to a low dome
    cap = [(0.50, 0.47), (0.55, 0.52), (0.56, 0.58), (0.52, 0.68), (0.43, 0.78), (0.30, 0.86), (0.16, 0.91), (0.0, 0.93)]
    centre = (0.0, 0.55, 0.0)
    lathe(m, cap, 28, CAP_TOP, wave=wave, tilt=tilt, outward=lambda c: sub(c, centre))

    # underside: gill ring from the rim in to the collar, facing down
    under = [(0.50, 0.47), (0.40, 0.49), (0.28, 0.52), (0.17, 0.555)]
    lathe(m, under, 28, GILLS, wave=lambda th, t: wave(th, 1 - t), tilt=tilt, outward=lambda c: (0.0, -1.0, 0.0))

    # bottom disc of the bulb, facing the floor
    lathe(m, [(0.20, 0.0), (0.0, 0.0)], 18, ROOTS, outward=lambda c: (0.0, -1.0, 0.0))

    # root tendrils: tapering tubes that creep out over the floor
    for k in range(6):
        a0 = TAU * k / 6 + random.uniform(-0.25, 0.25)
        length = random.uniform(0.28, 0.45)
        pts = []
        for i in range(8):
            t = i / 7
            d = 0.16 + length * t
            a = a0 + 0.35 * math.sin(t * 2.2 + k)
            pts.append(((d * math.cos(a), 0.06 * (1 - t) + 0.015, d * math.sin(a)), 0.045 * (1 - t) + 0.008))
        tube(m, pts, 6, ROOTS)

    m.save(os.path.join(out, 'gloomcap.obj'), 'Gloomcap')
    gloomcap_texture(os.path.join(out, 'gloomcap.png'))


def tube(m, pts, sides, box, v_scale=1.0, u_off=0.0):
    """A tube along pts [(pos, radius)], capped at the far end by shrinking to a point."""
    rows = []
    up = (0.0, 1.0, 0.0)
    n = len(pts)
    for i, (p, r) in enumerate(pts):
        nxt = pts[min(i + 1, n - 1)][0]; prv = pts[max(i - 1, 0)][0]
        tdir = norm(sub(nxt, prv))
        ref = up if abs(dot(tdir, up)) < 0.9 else (1.0, 0.0, 0.0)
        bx = norm(cross(tdir, ref)); by = norm(cross(bx, tdir))
        ring = []
        for s in range(sides + 1):
            th = TAU * s / sides
            q = add(p, add(mul(bx, r * math.cos(th)), mul(by, r * math.sin(th))))
            ring.append((q, region((s / sides + u_off) % 1.0001, (i / (n - 1)) * v_scale, box)))
        rows.append(ring)
    centres = [p for (p, _) in pts]
    def outward(c):
        # away from the nearest point on the spine
        best = min(centres, key=lambda q: dot(sub(c, q), sub(c, q)))
        return sub(c, best)
    m.grid(rows, outward=outward)


def gloomcap_texture(path, size=512):
    random.seed(11)
    img = Image.new('RGB', (size, size))
    d = ImageDraw.Draw(img)
    h = size // 2
    # atlas: v=0 is the bottom of the image in OBJ, so v0..v1 maps to rows size-v1*size .. size-v0*size
    def rect(box): return (int(box[0] * size), int(size - box[3] * size), int(box[2] * size), int(size - box[1] * size))

    # cap top: bruised violet-brown, darker towards the rim, with glowing pores
    x0, y0, x1, y1 = rect(CAP_TOP)
    for y in range(y0, y1):
        t = (y - y0) / (y1 - y0)  # 0 = apex (v=1 at top of box) ... 1 = rim
        r = int(70 - 30 * t); g = int(38 - 14 * t); b = int(82 - 26 * t)
        d.line([(x0, y), (x1, y)], fill=(r, g, b))
    for _ in range(900):  # mottling
        x = random.randint(x0, x1 - 1); y = random.randint(y0, y1 - 1); s = random.randint(2, 7)
        c = random.choice([(52, 26, 60), (88, 52, 96), (40, 22, 44)])
        d.ellipse([x - s, y - s, x + s, y + s], fill=c)
    pores = Image.new('RGB', (x1 - x0, y1 - y0), (0, 0, 0))
    pd = ImageDraw.Draw(pores)
    for _ in range(70):
        x = random.randint(4, x1 - x0 - 5); y = random.randint(int((y1 - y0) * 0.1), y1 - y0 - 8); s = random.randint(3, 8)
        pd.ellipse([x - s, y - s, x + s, y + s], fill=(90, 255, 170))
        pd.ellipse([x - s // 3, y - s // 3, x + s // 3, y + s // 3], fill=(220, 255, 235))
    # the pores light up the flesh around them: a soft halo, then the sharp pore on top
    glow = pores.filter(ImageFilter.GaussianBlur(4))
    cap_img = _screen(_screen(img.crop((x0, y0, x1, y1)), glow), pores)
    img.paste(cap_img, (x0, y0))

    # gills: fine radial lamellae, pale lilac with a faint green bloom near the collar
    x0, y0, x1, y1 = rect(GILLS)
    d.rectangle([x0, y0, x1, y1], fill=(96, 72, 104))
    for x in range(x0, x1, 3):
        d.line([(x, y0), (x, y1)], fill=(140, 112, 150) if (x // 3) % 2 else (70, 50, 78))
    for y in range(y0, y1):
        t = (y - y0) / (y1 - y0)
        if t > 0.7:
            k = (t - 0.7) / 0.3
            for x in range(x0, x1, 6): d.point((x, y), fill=(int(90 + 60 * k), int(130 + 90 * k), int(110 + 40 * k)))

    # stem: pale grey-violet with vertical fibres and a darker bulb
    x0, y0, x1, y1 = rect(STEM)
    for y in range(y0, y1):
        t = (y - y0) / (y1 - y0)  # 0 = top of stem
        c = (int(150 - 50 * t), int(138 - 52 * t), int(158 - 46 * t))
        d.line([(x0, y), (x1, y)], fill=c)
    for _ in range(260):
        x = random.randint(x0, x1); y = random.randint(y0, y1 - 20); l = random.randint(10, 40)
        d.line([(x, y), (x + random.randint(-2, 2), y + l)], fill=(118, 104, 128), width=1)

    # roots: dark knotted brown-purple
    x0, y0, x1, y1 = rect(ROOTS)
    d.rectangle([x0, y0, x1, y1], fill=(46, 30, 40))
    for _ in range(400):
        x = random.randint(x0, x1); y = random.randint(y0, y1); s = random.randint(1, 4)
        d.ellipse([x - s, y - s, x + s, y + s], fill=random.choice([(62, 40, 52), (34, 22, 30), (70, 54, 74)]))

    img = img.filter(ImageFilter.SMOOTH)
    img.save(path)
    print('wrote', path)


def _screen(a, b):
    """Screen blend (light adds without clipping hard)."""
    pa, pb = a.load(), b.load()
    out = Image.new('RGB', a.size)
    po = out.load()
    for y in range(a.size[1]):
        for x in range(a.size[0]):
            ca, cb = pa[x, y], pb[x, y]
            po[x, y] = tuple(255 - (255 - ca[i]) * (255 - cb[i]) // 255 for i in range(3))
    return out


# --------------------------------------------------------------------------------------------- Spillnode

THREAD, CORE = (0, 0, .75, 1), (.75, 0, 1, 1)


def spillnode(out):
    random.seed(3)
    m = Mesh()
    # a (2,3) torus knot: the thread loops back through itself
    R, r0, n = 0.24, 0.10, 150
    pts = []
    for i in range(n + 1):
        t = TAU * i / n
        q = 2 * t
        rr = R + r0 * math.cos(3 * t)
        p = (rr * math.cos(q), r0 * math.sin(3 * t) * 1.2, rr * math.sin(q))
        pts.append((p, 0.032 + 0.012 * math.sin(6 * t + 1.0)))
    tube(m, pts, 8, THREAD, v_scale=1.0)

    # loose ends: three frayed threads trailing off the knot
    for k in range(3):
        a = TAU * k / 3 + 0.4
        start = (0.30 * math.cos(a), 0.05 * (k - 1), 0.30 * math.sin(a))
        trail = []
        for i in range(7):
            t = i / 6
            d = 0.30 + 0.22 * t
            ang = a + 0.6 * t
            trail.append(((d * math.cos(ang), start[1] + 0.12 * math.sin(t * 3 + k), d * math.sin(ang)), 0.022 * (1 - t) + 0.004))
        tube(m, trail, 5, THREAD, v_scale=0.3, u_off=0.0)

    # the core: a small faceted bead where the power is still held
    core_profile = [(0.0, -0.085), (0.06, -0.06), (0.085, 0.0), (0.06, 0.06), (0.0, 0.085)]
    lathe(m, core_profile, 12, CORE, outward=lambda c: c)

    m.save(os.path.join(out, 'spillnode.obj'), 'Spillnode')
    spillnode_texture(os.path.join(out, 'spillnode.png'))


def spillnode_texture(path, size=256):
    img = Image.new('RGB', (size, size))
    d = ImageDraw.Draw(img)
    # thread: along the knot (v) the colour cycles heat -> white -> frost -> static violet -> heat
    stops = [(0.0, (255, 120, 40)), (0.2, (255, 220, 160)), (0.38, (120, 220, 255)), (0.6, (60, 120, 255)),
             (0.8, (190, 110, 255)), (1.0, (255, 120, 40))]
    def col(t):
        for (a, ca), (b, cb) in zip(stops, stops[1:]):
            if a <= t <= b:
                k = (t - a) / (b - a)
                return tuple(int(ca[i] + (cb[i] - ca[i]) * k) for i in range(3))
        return stops[-1][1]
    x1 = int(THREAD[2] * size)
    for y in range(size):
        t = 1 - y / (size - 1)
        c = col(t)
        for x in range(x1):
            # a bright filament down the middle of the thread (u wraps around the tube)
            u = x / x1
            k = 0.55 + 0.45 * math.cos(u * TAU * 2)
            d.point((x, y), fill=tuple(min(255, int(c[i] * (0.6 + 0.5 * k))) for i in range(3)))
    # core: hot white fading to pale lilac
    for y in range(size):
        t = abs(y / (size - 1) - 0.5) * 2
        c = (255, int(250 - 40 * t), int(255 - 20 * t))
        d.line([(x1, y), (size, y)], fill=c)
    img.save(path)
    print('wrote', path)


# ------------------------------------------------------------------------------------------- Omega wisp

HALO, SHARD, OCORE = (0, 0, .5, 1), (.5, 0, .75, 1), (.75, 0, 1, 1)


def shard(m, base, tip, w, box):
    """A long six-sided crystal from base to tip, widest a third of the way up."""
    axis = norm(sub(tip, base))
    side = norm(cross(axis, (0, 1, 0) if abs(axis[1]) < 0.9 else (1, 0, 0)))
    up = cross(side, axis)
    mid = add(base, mul(sub(tip, base), 0.33))
    ring = [add(mid, add(mul(side, w * math.cos(TAU * i / 6)), mul(up, w * math.sin(TAU * i / 6)))) for i in range(6)]
    cb = m.vert(base, region(0.5, 0.0, box)); ct = m.vert(tip, region(0.5, 1.0, box))
    rv = [m.vert(q, region(i / 6, 0.33, box)) for i, q in enumerate(ring)]
    centre = mul(add(base, tip), 0.5)
    out = lambda c: sub(c, centre)
    for i in range(6):
        a, b = rv[i], rv[(i + 1) % 6]
        m.face(cb, a, b, out)
        m.face(a, ct, b, out)


def omega_wisp(out):
    random.seed(11)
    m = Mesh()
    # the core: a faceted bead of mind light (few segments so the facets catch the glow)
    core = [(0.0, -0.16), (0.09, -0.12), (0.14, -0.03), (0.13, 0.05), (0.08, 0.13), (0.0, 0.17)]
    lathe(m, core, 7, OCORE, outward=lambda c: c)
    # the halo: a thin ring tilted across the core
    tilt = math.radians(24)
    pts = []
    for i in range(73):
        a = TAU * i / 72
        x, z = 0.27 * math.cos(a), 0.27 * math.sin(a)
        pts.append(((x, z * math.sin(tilt), z * math.cos(tilt)), 0.016))
    tube(m, pts, 6, HALO, v_scale=2.0)
    # six frost shards ringing the core, pointing outward and a little up or down
    for k in range(6):
        a = TAU * k / 6 + random.uniform(-0.15, 0.15)
        lift = 0.10 if k % 2 == 0 else -0.08
        d0, d1 = 0.17, 0.36 + random.uniform(0.0, 0.06)
        base = (d0 * math.cos(a), lift * 0.5, d0 * math.sin(a))
        tip = (d1 * math.cos(a), lift * 1.6, d1 * math.sin(a))
        shard(m, base, tip, 0.028, SHARD)
    m.save(os.path.join(out, 'omega_wisp.obj'), 'Omega Hoarlight')
    omega_wisp_texture(os.path.join(out, 'omega_wisp.png'))


def omega_wisp_texture(path, size=256):
    img = Image.new('RGB', (size, size))
    d = ImageDraw.Draw(img)
    x_halo, x_shard = int(HALO[2] * size), int(SHARD[2] * size)
    for y in range(size):
        t = y / (size - 1)
        # halo: pale silver-blue with bright bands running round the ring
        k = 0.5 + 0.5 * math.cos(t * TAU * 6)
        d.line([(0, y), (x_halo, y)], fill=(int(150 + 90 * k), int(200 + 50 * k), 255))
        # shards: deep frost at the root to near-white at the tip (v runs root -> tip, image top = v 1)
        v = 1 - t
        d.line([(x_halo, y), (x_shard, y)], fill=(int(70 + 175 * v), int(150 + 100 * v), 255))
        # core: white-hot centre fading to cold violet at the poles
        c = abs(v - 0.5) * 2
        d.line([(x_shard, y), (size, y)], fill=(int(255 - 70 * c), int(255 - 90 * c), 255))
    img = img.filter(ImageFilter.GaussianBlur(1))
    img.save(path)
    print('wrote', path)


def hoarlight(out):
    random.seed(5)
    m = Mesh()
    # a teardrop crystal, point up; six facets so it glints as it turns
    core = [(0.0, -0.13), (0.06, -0.06), (0.075, 0.0), (0.055, 0.07), (0.025, 0.12), (0.0, 0.16)]
    lathe(m, core, 6, OCORE, outward=lambda c: c)
    # three splinters hanging off its waist, tipped down like icicles
    for k in range(3):
        a = TAU * k / 3 + random.uniform(-0.2, 0.2)
        base = (0.05 * math.cos(a), -0.01, 0.05 * math.sin(a))
        tip = (0.15 * math.cos(a), -0.09, 0.15 * math.sin(a))
        shard(m, base, tip, 0.018, SHARD)
    m.save(os.path.join(out, 'hoarlight.obj'), 'Hoarlight')
    omega_wisp_texture(os.path.join(out, 'hoarlight.png'))  # same atlas layout: core, shards


def shardspark(out):
    random.seed(17)
    m = Mesh()
    # three splinters crossed through one point, each sticking out both ways, uneven like a break
    dirs = [(1.0, 0.35, 0.2), (-0.3, 1.0, 0.45), (0.25, -0.4, 1.0)]
    for d in dirs:
        d = norm(d)
        a, b = random.uniform(0.13, 0.19), random.uniform(0.08, 0.13)
        shard(m, mul(d, -b), mul(d, a), 0.024, SHARD)
    core = [(0.0, -0.045), (0.04, 0.0), (0.0, 0.045)]
    lathe(m, core, 5, OCORE, outward=lambda c: c)
    m.save(os.path.join(out, 'shardspark.obj'), 'Shardspark')
    omega_wisp_texture(os.path.join(out, 'shardspark.png'))


